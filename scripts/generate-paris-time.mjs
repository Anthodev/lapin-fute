import { writeFile } from "node:fs/promises";

// Build-time ICU is the source of truth. Phone code uses only UTC Date accessors.
const MAX_SECONDS = 0xffffffff;
const formatter = new Intl.DateTimeFormat("en-GB-u-nu-latn", {
  timeZone: "Europe/Paris",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
  second: "2-digit",
  hourCycle: "h23",
});

function offsetAt(seconds) {
  const values = {};
  for (const part of formatter.formatToParts(new Date(seconds * 1000))) {
    if (part.type !== "literal") values[part.type] = Number(part.value);
  }
  const local = Date.UTC(values.year, values.month - 1, values.day, values.hour, values.minute, values.second) / 1000;
  const offset = local - seconds;
  if (!Number.isInteger(offset) || Math.abs(offset) > 86400) {
    throw new Error("Build-time ICU did not produce a valid Europe/Paris UTC offset");
  }
  return offset;
}

const transitions = [0, offsetAt(0)];
let previous = 0;
let previousOffset = transitions[1];
while (previous < MAX_SECONDS) {
  // Paris never has two offset transitions in the same UTC day.
  const probe = Math.min(previous + 86400, MAX_SECONDS);
  const nextOffset = offsetAt(probe);
  if (nextOffset !== previousOffset) {
    let low = previous + 1;
    let high = probe;
    while (low < high) {
      const middle = Math.floor((low + high) / 2);
      if (offsetAt(middle) === previousOffset) low = middle + 1;
      else high = middle;
    }
    transitions.push(low, nextOffset);
    previousOffset = nextOffset;
  }
  previous = probe;
}

const rows = [];
for (let index = 0; index < transitions.length; index += 12) {
  rows.push("  " + transitions.slice(index, index + 12).join(", "));
}
const source = `"use strict";

// Generated by scripts/generate-paris-time.mjs from ICU Europe/Paris.
// tzdb ${process.versions.tz}; covers every uint32 epoch second, including 2106-02-07.
var TRANSITIONS = [
${rows.join(",\n")}
];

function twoDigits(value) {
  return value < 10 ? "0" + value : String(value);
}

function currentParisTimestamp(milliseconds) {
  var seconds;
  var low = 0;
  var high = TRANSITIONS.length / 2 - 1;
  var middle;
  var date;
  if (typeof milliseconds !== "number" || !isFinite(milliseconds)
      || milliseconds < 0 || milliseconds >= 4294967296000) {
    throw new RangeError("Paris time requires uint32 epoch seconds");
  }
  seconds = Math.floor(milliseconds / 1000);
  while (low < high) {
    middle = Math.floor((low + high + 1) / 2);
    if (TRANSITIONS[middle * 2] <= seconds) low = middle;
    else high = middle - 1;
  }
  date = new Date((seconds + TRANSITIONS[low * 2 + 1]) * 1000);
  return String(date.getUTCFullYear()) + twoDigits(date.getUTCMonth() + 1)
    + twoDigits(date.getUTCDate()) + "T" + twoDigits(date.getUTCHours())
    + twoDigits(date.getUTCMinutes()) + twoDigits(date.getUTCSeconds());
}

module.exports = currentParisTimestamp;
`;
await writeFile(new URL("../packages/companion/src/compactparis-time.js", import.meta.url), source);
console.log(`Generated Europe/Paris transition table: ${transitions.length / 2} entries, tzdb ${process.versions.tz}`);
