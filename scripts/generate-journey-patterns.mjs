import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const companion = new URL("../packages/companion/src/", import.meta.url);
const output = new URL("../packages/config-page/src/generated/", import.meta.url);
const names = [
  "JOURNEY_LIMITS", "normalizeDestinationLabel", "isServiceJourneyDocument",
  "isJourneyGroupIndex", "isJourneyGroupPage", "validateJourneyGroup",
  "reachableArrivals", "createJourneyClassifier", "arrivalLabel", "journeyKey",
];

export function generateJourneyPatterns() {
  const contracts = readFileSync(new URL("contracts.js", companion), "utf8");
  const journeys = readFileSync(new URL("journey-patterns.js", companion), "utf8");
  // Deliberately reject every other use of require, including indirect calls.
  // This is a closed two-module generator, not a dependency resolver.
  if (/\brequire\b/u.test(contracts)
      || /\brequire\b/u.test(journeys.replace(/\brequire\("\.\/contracts"\)/gu, ""))) {
    throw new Error("Unsupported dependency in shared journey sources");
  }
  const source = "// Generated by scripts/generate-journey-patterns.mjs. Do not edit.\n"
    + "const contractsModule = { exports: {} };\n"
    + "(function (module) {\n" + contracts + "\n})(contractsModule);\n"
    + "const journeyModule = { exports: {} };\n"
    + "(function (module, require) {\n" + journeys + "\n})(journeyModule, function (name) {\n"
    + "  if (name !== \"./contracts\") throw new Error(\"Unsupported journey dependency\");\n"
    + "  return contractsModule.exports;\n});\n"
    + names.map(name => `export const ${name} = journeyModule.exports.${name};\n`).join("");
  mkdirSync(output, { recursive: true });
  writeFileSync(new URL("journey-patterns.js", output), source);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generateJourneyPatterns();
